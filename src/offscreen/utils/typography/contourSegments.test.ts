import { describe, it, expect, beforeAll, beforeEach } from 'vitest';
import {
  buildContourSegments,
  computeLineBreakOpportunities,
  isContourHyphenationReady,
  type ContourSegmentTemplate,
} from './contourSegments';
import { HyphenationService, loadHyphenationLanguage } from '../hyphenation';

/**
 * Reconstructs the visible text from templates to assert source fidelity.
 *
 * @param text - Original text.
 * @param segments - Templates.
 * @returns Concatenated visible ranges.
 */
function visibleText(text: string, segments: ContourSegmentTemplate[]): string {
  return segments.map((s) => text.slice(s.range.start, s.range.end)).join('');
}

describe('contourSegments donor port', () => {
  beforeAll(async () => {
    await loadHyphenationLanguage('en');
  });

  beforeEach(() => {
    // Keep the trie loaded across tests; only reset word caches would change policy.
    expect(isContourHyphenationReady('en')).toBe(true);
  });

  it('hypher trie reproduces donor English syllables', () => {
    const service = HyphenationService.getInstance();
    expect(service.contourSyllables('extensive', 'en', 2, 3)).toEqual(['ex', 'ten', 'sive']);
    expect(service.contourSyllables('walking', 'en', 2, 3)).toEqual(['walk', 'ing']);
    expect(service.contourSyllables('whatever', 'en', 2, 3)).toEqual(['what', 'ever']);
  });

  it('reproduces donor multilingual vectors from hypher 0.1.8', async () => {
    // Provenance: hypher 0.1.8 src/lib.rs tests (crate VCS d81cc506), not
    // expectations generated by the TypeScript implementation under test.
    const service = HyphenationService.getInstance();
    const cases: Array<[string, string, string, number, number]> = [
      // lang, word, expected hyphen-joined, left, right
      ['de', 'gehen', 'ge-hen', 2, 2],
      ['de', 'Apfel', 'Ap-fel', 2, 2],
      ['de', 'Tomate', 'To-ma-te', 2, 2],
      ['de', 'Eingabeaufforderung', 'Ein-ga-be-auf-for-de-rung', 2, 2],
      ['de', 'Fortpflanzungslemma', 'Fort-pflan-zungs-lem-ma', 2, 2],
      ['de', 'hässlich', 'häss-lich', 2, 2],
      ['fi', 'äänioikeus', 'ää-ni-oi-keus', 2, 2],
      ['fi', 'yliopisto', 'yli-o-pis-to', 2, 2],
      ['fi', 'ravintola', 'ra-vin-to-la', 2, 2],
      ['fi', 'sanakirja', 'sa-na-kir-ja', 2, 2],
      ['el', 'διαμερίσματα', 'δια-με-ρί-σμα-τα', 1, 1],
      ['cs', 'povídáme', 'po-ví-dá-me', 2, 2],
      ['ml', 'വിദ്യാർത്ഥി', 'വി-ദ്യാർ-ത്ഥി', 2, 2],
      ['hi', 'विद्यार्थी', 'वि-द्या-र्थी', 2, 2],
    ];
    for (const [lang, word, expected, left, right] of cases) {
      await loadHyphenationLanguage(lang);
      expect(service.contourSyllables(word, lang, left, right).join('-'), `${lang}:${word}`).toBe(expected);
    }
  });

  it('does not invent breaks missing from the patterns (idols)', () => {
    const text = 'idols';
    const segments = buildContourSegments(text, 'en');
    expect(segments).toHaveLength(1);
    expect(segments[0].range).toEqual({ start: 0, end: 5 });
    expect(segments[0].breakSuffix).toBeNull();
  });

  it('hyphenates a long word and keeps source indices contiguous', () => {
    const text = 'antidisestablishmentarianism';
    const segments = buildContourSegments(text, 'en', { minimumWordLength: 8 });
    expect(segments.length).toBeGreaterThan(1);
    expect(visibleText(text, segments)).toBe(text);
    for (let i = 0; i < segments.length - 1; i++) {
      expect(segments[i].breakSuffix).toBe('-');
      expect(segments[i].nextOffset).toBe(segments[i].range.end);
      expect(segments[i].isMandatory).toBe(false);
    }
    expect(segments[segments.length - 1].breakSuffix).toBeNull();
    expect(segments[segments.length - 1].nextOffset).toBe(text.length);
  });

  it('honors 5-7 letter eligibility and explicit fragment bounds', () => {
    // English default right bound is 3, so "tower" -> "tow"/"er" is forbidden.
    const strict = buildContourSegments('tower', 'en', { minimumWordLength: 5 });
    expect(strict).toHaveLength(1);

    // Explicit donor-style bounds (2,2) allow "tow"/"er".
    const relaxed = buildContourSegments('tower', 'en', {
      minimumWordLength: 5,
      minimumPrefixLength: 2,
      minimumSuffixLength: 2,
    });
    expect(relaxed.map((s) => 'tower'.slice(s.range.start, s.range.end))).toEqual(['tow', 'er']);
    expect(relaxed[0].breakSuffix).toBe('-');
    expect(relaxed[1].breakSuffix).toBeNull();
  });

  it('keeps Unicode punctuation in the source range around the hyphenated core', () => {
    const text = '\u201cextraordinary,\u201d';
    const segments = buildContourSegments(text, 'en', { minimumWordLength: 8 });
    expect(segments.length).toBeGreaterThan(1);
    expect(visibleText(text, segments)).toBe(text);
    // Opening quote belongs to the first visible slice.
    expect(text.slice(segments[0].range.start, segments[0].range.end).startsWith('\u201c')).toBe(true);
    // Closing comma/quote belong to the final visible slice.
    expect(text.slice(segments[segments.length - 1].range.start, segments[segments.length - 1].range.end).endsWith(',\u201d')).toBe(true);
  });

  it('retains hard hyphens and never hyphenates across them', () => {
    const text = 'well-known';
    const segments = buildContourSegments(text, 'en', { minimumWordLength: 5 });
    // UAX #14 legitimately allows a break after the authored hyphen, so two
    // segments are expected. Neither half is short enough to hyphenate further,
    // and no synthetic suffix may be invented across the hard hyphen.
    expect(segments).toHaveLength(2);
    expect(segments.map((s) => text.slice(s.range.start, s.range.end))).toEqual(['well-', 'known']);
    expect(segments[0].breakSuffix).toBeNull();
    expect(segments[1].breakSuffix).toBeNull();
    expect(segments[0].nextOffset).toBe(5);
    expect(segments[1].nextOffset).toBe(text.length);
  });

  it('trims mandatory break chars from range but preserves them in nextOffset', () => {
    const text = 'Hello, \nWorld!';
    const segments = buildContourSegments(text, 'en');
    expect(segments).toHaveLength(2);

    expect(text.slice(segments[0].range.start, segments[0].range.end)).toBe('Hello, ');
    expect(segments[0].nextOffset).toBe(8);
    expect(segments[0].isMandatory).toBe(true);
    expect(segments[0].breakSuffix).toBeNull();

    expect(text.slice(segments[1].range.start, segments[1].range.end)).toBe('World!');
    expect(segments[1].nextOffset).toBe(text.length);
    expect(segments[1].isMandatory).toBe(false);
  });

  it('does not hyphenate mandatory segments', () => {
    const text = 'extraordinary\n';
    const segments = buildContourSegments(text, 'en', { minimumWordLength: 8 });
    // Mandatory segment stays whole; trailing newline is trimmed from range.
    expect(segments).toHaveLength(1);
    expect(segments[0].isMandatory).toBe(true);
    expect(segments[0].range.end).toBe('extraordinary'.length);
    expect(segments[0].nextOffset).toBe(text.length);
  });

  it('accepts caller-supplied opportunities for exact donor parity', () => {
    const text = 'extraordinary';
    const opportunities = [
      { offset: 0, isMandatory: false },
      { offset: text.length, isMandatory: false },
    ];
    const segments = buildContourSegments(text, 'en', {
      minimumWordLength: 8,
      opportunities,
    });
    expect(segments.length).toBeGreaterThan(1);
    expect(visibleText(text, segments)).toBe(text);
  });

  it('keeps Korean words whole under the KeepAll approximation', () => {
    const text = 'B6층 모험가들이 돌아갔으니까 청소 부탁해';
    const opportunities = computeLineBreakOpportunities(text);
    const pieces = opportunities
      .slice(0, -1)
      .map((op, i) => text.slice(op.offset, opportunities[i + 1].offset));
    expect(pieces).toEqual(['B6층 ', '모험가들이 ', '돌아갔으니까 ', '청소 ', '부탁해']);
  });

  it('never falls back to legacy heuristic hyphenation when trie is absent', async () => {
    // 'ro' has a legacy Liang dictionary but no hypher trie in donor data.
    HyphenationService.resetInstance();
    await loadHyphenationLanguage('ro');
    const segments = buildContourSegments('extraordinar', 'ro', { minimumWordLength: 5 });
    // No hypher trie -> no discretionary splits (and no legacy fallback).
    expect(segments).toHaveLength(1);
    expect(segments[0].breakSuffix).toBeNull();
    // Restore English trie for any later tests.
    await loadHyphenationLanguage('en');
  });
});